const cache = new Map<string, string>();
export function adviceRaj(en: string): string {
  const k = en.trim(); if (FIX[k]) return FIX[k];
  const hi = ADVICE_HI[k]; if (!hi) return '';
  let r = cache.get(k); if (r === undefined) { r = convert(hi); cache.set(k, r); }
  return r;
}
