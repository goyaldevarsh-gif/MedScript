/** polite commands: करें -> करज्यो, जाएँ -> जाज्यो, लें -> लीज्यो */
const CMD: Record<string, string> = { 'लें': 'लीज्यो', 'दें': 'दीज्यो', 'पिएँ': 'पीज्यो', 'सोएँ': 'सोज्यो', 'रखें': 'राखज्यो', 'पहनें': 'पहरज्यो', 'पहनाएँ': 'पहराज्यो', 'नहाएँ': 'न्हाज्यो', 'बैठें': 'बैठज्यो', 'चलें': 'चालज्यो', 'उठाएँ': 'उठाज्यो', 'करें': 'करज्यो', 'बचें': 'बचज्यो', 'दिखाएँ': 'दिखाज्यो', 'लाएँ': 'ल्याज्यो', 'मोड़ें': 'मोड़ज्यो', 'डालें': 'घालज्यो', 'लगाएँ': 'लगाज्यो', 'खाएँ': 'खाज्यो', 'रहें': 'रहज्यो', 'बदलें': 'बदलज्यो', 'देखें': 'देखज्यो', 'हटाएँ': 'हटाज्यो', 'शुरू': 'शुरू', 'छोड़ें': 'छोड़ज्यो', 'हिलाएँ': 'हिलाज्यो', 'सुलाएँ': 'सुलाज्यो', 'चढ़ें': 'चढ़ज्यो', 'मरोड़ें': 'मरोड़ज्यो', 'जमें': 'जमज्यो', 'सोचें': 'सोचज्यो', 'पूछें': 'पूछज्यो', 'बनाएँ': 'बणाज्यो', 'रोकें': 'रोकज्यो', 'बाँधें': 'बांधज्यो', 'खोलें': 'खोलज्यो', 'घुमाएँ': 'घुमाज्यो', 'निकलवाएँ': 'निकलवाज्यो', 'बताएँ': 'बताज्यो' };
function convert(hi: string): string {
  hi = hi.replace(/हो जाए/g, 'हो जावै').replace(/न हो पाएँ/g, 'ना हो सकै').replace(/होता है/g, 'होवै').replace(/न पाएँ/g, 'ना सकै');
  const tok = hi.split(/([\s,;:()\/।-]+)/);
  const out = tok.map((x, i) => (x === 'जाएँ' && !/(में|इमरजेंसी)\s*$/.test(tok.slice(Math.max(0, i - 2), i).join(''))) ? 'जावै' : (CMD[x] ?? W[x] ?? x));
  let t = out.join('');
  t = t.replace(/(^|[ ,;:(])न ([\u0900-\u097F]+ज्यो)/g, '$1मत $2');
  return t.replace(/होवै जावै/g, 'हो जावै').replace(/ना होवै सकै/g, 'ना हो सकै').replace(/ +/g, ' ').trim();
}
